"""Reconcile delivered Chapters 1-4 with their pre-drafting plans (free; no API).

  python -I -X utf8 drafting/_tools/reconcile.py
    -> editorial/wholebook/delivered_chNN.json   (as-delivered structure: sections, words, paragraphs, IDs, opening/closing)
    -> editorial/wholebook/reconcile_report.md   (plan-versus-delivered divergences, for review; nothing is decided here)

Word counts are the validator's (inhouse.py check, notes and IDs excluded).
Paragraph matching: each delivered paragraph is paired with the plan paragraph of the same section whose evidence IDs
overlap most (Jaccard); pairs below 0.15 count as unmatched.
"""
import json
import os
import re
import subprocess
import sys
from pathlib import Path

DR = Path(__file__).resolve().parent.parent
OUT = DR / "editorial" / "wholebook"
sys.path.insert(0, str(DR / "_tools"))
import stitch  # noqa: E402

ID = re.compile(r"\bC\d\d-[A-Z0-9]+(?:-[A-Z0-9]+)*?-\d{3}\b")
NOTE = re.compile(r"\{\{note:(.*?)\}\}", re.S)
TIERS = {}
for f in (DR / "evidence_index").glob("ch*.jsonl"):
    for line in f.open(encoding="utf-8"):
        r = json.loads(line)
        TIERS[r["id"]] = r["tier"]


def tier(i):
    return f"T{TIERS[i]}" if i in TIERS else "T?"


def plan_sections(text, ch):
    secs = {}
    for part in re.split(rf"\n(?=## {ch}\.\d )", text)[1:]:
        k = re.match(rf"## ({ch}\.\d)", part).group(1)
        head = part.split("\n", 1)[0]
        title = re.match(rf"## {ch}\.\d (.+?)\s*\*\(", head).group(1)
        tgt = int(re.search(r"(\d[\d,]*)\s*w\b", head).group(1).replace(",", ""))
        stmt = re.search(r"\*\*Section statement:\*\*\s*(.+?)(?=\n\*\*|\n\n\*\*)", part, re.S)
        trans = re.search(r"\*\*Transition(?: \(out[^)]*\))?:\*\*\s*(.+)", part)
        paras = []
        for pm in re.finditer(r"^\s*\d+[a-z]?\. \*\*(P\d+[a-z]?)\s*[—-]\s*(.+?)\*\*(.*?)(?=^\s*\d+[a-z]?\. \*\*P|^\*\*Transition|\Z)", part, re.S | re.M):
            body = pm.group(3)
            point = re.search(r"\*\*Point:\*\*\s*(.+?)(?=\n\s*- (?:E|C|X|Note|[A-Z][a-z]+ note):|\Z)", body, re.S)
            roles = {}
            for line in body.split("\n"):
                s = line.strip().lstrip("- ")
                for seg in re.split(r"(?<=\.)\s+(?=(?:E|C|X|Note|[A-Z][a-z]+ note):)", s):
                    m = re.match(r"(E|C|X|Note|[A-Z][a-z]+ note):\s*(.*)", seg)
                    if m:
                        role = "Note" if "note" in m.group(1).lower() else m.group(1)
                        for i in ID.findall(m.group(2)):
                            roles.setdefault(i, role)
            paras.append({"p": pm.group(1), "title": pm.group(2).strip().rstrip("."), "point": re.sub(r"\s+", " ", point.group(1)).strip() if point else "",
                          "roles": roles})
        secs[k] = {"title": title, "target": tgt, "statement": re.sub(r"\s+", " ", stmt.group(1)).strip() if stmt else "",
                   "transition": trans.group(1).strip() if trans else "", "paras": paras}
    return secs


def words_of(cfg, sec):
    env = dict(os.environ, UDAY_CFG=str(cfg), PYTHONIOENCODING="utf-8")
    r = subprocess.run([sys.executable, "-I", "-X", "utf8", str(DR / "_pipe" / "inhouse.py"), "check", sec], cwd=DR / "_pipe",
                       env=env, capture_output=True, text=True, encoding="utf-8")
    return json.loads(r.stdout)["words"]


def first_sentence(t):
    t = re.sub(r"\s*\[C\d\d-[^\]]*\]", "", NOTE.sub("", t)).strip()
    m = re.match(r"(.+?[.!?][”’\"]?)(?=\s+[A-Z“‘]|$)", t, re.S)
    return re.sub(r"\s+", " ", (m.group(1) if m else t)).strip()


def last_sentence(t):
    t = re.sub(r"\s*\[C\d\d-[^\]]*\]", "", NOTE.sub("", t)).strip()
    parts = re.split(r"(?:(?<=[.!?])|(?<=[.!?][”’\"]))\s+(?=[A-Z“‘])", t)
    return re.sub(r"\s+", " ", parts[-1]).strip()


def jac(a, b):
    return len(a & b) / len(a | b) if a | b else 0.0


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    rep = ["# Chapters 1–4: plan versus delivered text", "",
           "*Generated by `_tools/reconcile.py` from the delivered sections (`run/chN/`) and each chapter's plan. Divergences are listed for review; none is resolved here.*", ""]
    for ch in (1, 2, 3, 4):
        C = stitch.load(ch)
        plan = plan_sections(C.OUTLINE.read_text(encoding="utf-8"), ch)
        cfgp = DR / stitch.CFG[ch]
        out = {"chapter": ch, "title": C.TITLE, "plan_file": C.OUTLINE.name, "sections": []}
        rep += [f"## Chapter {ch}. {C.TITLE}", "", f"Plan: `{C.OUTLINE.relative_to(DR)}`. Delivered: `run/ch{ch}/`.", "",
                "| Section | Plan title / target | Delivered title / words | Share | Plan ¶ | Delivered ¶ |", "|---|---|---|---|---|---|"]
        notes = []
        all_ids = set()
        for sec in C.SECTIONS:
            t = (DR / "run" / f"ch{ch}" / f"{sec}.md").read_text(encoding="utf-8").strip()
            head, body = t.split("\n", 1)
            dtitle = re.sub(rf"^## {sec}\s+", "", head).strip()
            paras = [p.strip() for p in re.split(r"\n\s*\n", body) if p.strip()]
            dps = []
            for k, p in enumerate(paras, 1):
                nids = set(ID.findall(" ".join(NOTE.findall(p))))
                bids = set(ID.findall(NOTE.sub("", p)))
                all_ids |= nids | bids
                dps.append({"n": k, "body_ids": sorted(bids), "note_ids": sorted(nids - bids), "first": first_sentence(p), "last": last_sentence(p),
                            "words": len(re.sub(r"\s*\[C\d\d-[^\]]*\]", "", NOTE.sub("", p)).split())})
            w = words_of(cfgp, sec)
            ps = plan.get(sec, {"title": "(not in plan)", "target": 0, "paras": [], "statement": "", "transition": ""})
            # match
            used = set()
            for d in dps:
                ids = set(d["body_ids"]) | set(d["note_ids"])
                best = max(((jac(ids, set(pp["roles"])), j) for j, pp in enumerate(ps["paras"])), default=(0, None))
                d["plan_match"] = ps["paras"][best[1]]["p"] if best[1] is not None and best[0] >= 0.15 else None
                d["match_score"] = round(best[0], 2)
                if d["plan_match"]:
                    used.add(d["plan_match"])
                    pp = ps["paras"][best[1]]
                    d["plan_title"], d["plan_point"] = pp["title"], pp["point"]
                    d["roles"] = {i: pp["roles"].get(i, "Note" if i in d["note_ids"] else "E") for i in sorted(ids)}
                else:
                    d["roles"] = {i: ("Note" if i in d["note_ids"] else "E") for i in sorted(ids)}
            for d in dps:
                for i in d["roles"]:
                    planned = [pp["roles"][i] for pp in ps["paras"] if i in pp["roles"]]
                    if planned:
                        d["roles"][i] = planned[0] if not (d["roles"][i] == "Note" and i in d["note_ids"]) else "Note"
            unmatched_plan = [pp for pp in ps["paras"] if pp["p"] not in used]
            planned_E = {i for pp in ps["paras"] for i, r in pp["roles"].items() if r == "E"}
            sec_ids = {i for d in dps for i in d["roles"]}
            missing_E = sorted(planned_E - sec_ids)
            added = sorted(sec_ids - {i for pp in ps["paras"] for i in pp["roles"]})
            out["sections"].append({"sec": sec, "title": dtitle, "plan_title": ps["title"], "target": ps["target"], "words": w,
                                    "statement": ps["statement"], "transition": ps["transition"], "paras": dps,
                                    "unmatched_plan": [{"p": pp["p"], "title": pp["title"], "point": pp["point"]} for pp in unmatched_plan],
                                    "missing_E": missing_E, "added": added})
            rep.append(f"| {sec} | {ps['title']} / {ps['target']} | {dtitle} / {w} | {round(100 * w / ps['target']) if ps['target'] else '—'}% | "
                       f"{len(ps['paras'])} | {len(dps)} |")
            if dtitle != ps["title"]:
                notes.append(f"- **{sec} title:** plan \"{ps['title']}\"; delivered \"{dtitle}\".")
            for pp in unmatched_plan:
                notes.append(f"- **{sec} {pp['p']} \"{pp['title']}\"**: no delivered paragraph shares its evidence (best overlap < 0.15). Planned point: {pp['point'][:260]}")
            for d in dps:
                if not d["plan_match"]:
                    notes.append(f"- **{sec} ¶{d['n']}** (delivered) matches no plan paragraph (best {d['match_score']}). Opens: \"{d['first'][:200]}\"")
            if missing_E:
                notes.append(f"- **{sec}** planned establishing items not cited in the delivered section: {', '.join(missing_E)}.")
            if added:
                notes.append(f"- **{sec}** items cited but not in the plan ({len(added)}): {', '.join(added)}.")
        first = out["sections"][0]["paras"][0]
        lastp = out["sections"][-1]["paras"][-1]
        out["opening"], out["closing"] = first["first"], lastp["last"]
        out["opening_para"] = first["first"]
        out["all_ids"] = sorted(all_ids)
        (OUT / f"delivered_ch{ch:02d}.json").write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding="utf-8")
        tot = sum(s["words"] for s in out["sections"])
        rep += ["", f"Delivered total: **{tot}** words. Opening sentence: \"{out['opening']}\". Closing sentence: \"{out['closing']}\".", "",
                "### Divergences (mechanical; each reviewed in `OUTLINE_WHOLEBOOK_CHANGES.md`)", ""] + (notes or ["- none"]) + [""]
        print(f"ch{ch}: {len(out['sections'])} sections, {tot} words, {len(notes)} divergence lines")
    (OUT / "reconcile_report.md").write_text("\n".join(rep) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
